for it in new_items:
    if it["item_id"] in existing_ids:
        errs.append(f"중복 item_id: {it['item_id']}")
    if len(it["choices"]) != 4:
        errs.append(f"{it['item_id']}: 선택지 4개 아님")
    if not (0 <= it["answer"] < 4):
        errs.append(f"{it['item_id']}: answer 범위 오류")
    if it["passage_id"] and it["passage_id"] not in valid_pids:
        errs.append(f"{it['item_id']}: 미존재 지문 {it['passage_id']}")
    existing_ids.add(it["item_id"])
if errs:
    print("검증 실패:\n" + "\n".join(errs)); raise SystemExit(1)

items.extend(new_items)
passages.extend(new_passages)

